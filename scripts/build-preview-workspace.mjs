import { build } from 'esbuild'
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'
import { assertOwnedBuildInputs } from './standalone-boundary.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
async function bundle(entry) {
return build({ absWorkingDir: root, entryPoints: [entry], bundle: true,
  write: false, platform: 'browser', format: 'iife', target: 'es2022', minify: true, metafile: true,
  jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'eof' })
}
const output = await bundle('ui/workspace.tsx'), importOutput = await bundle('ui/import-review.tsx')
const inputs = [...new Set([...Object.keys(output.metafile.inputs), ...Object.keys(importOutput.metafile.inputs)])]
await assertOwnedBuildInputs(root, inputs)
for (const artifact of [...Object.values(output.metafile.outputs), ...Object.values(importOutput.metafile.outputs)])
  if (artifact.imports.length) throw Error('Preview must not need external scripts.')
const notice = await readFile(resolve(root, 'notices/animate-ui.txt'), 'utf8')
const packages = new Map()
for (const input of inputs) {
  if (!input.startsWith('node_modules/')) continue
  const parts = input.split('/'), directory = parts.slice(0, parts[1].startsWith('@') ? 3 : 2).join('/')
  if (packages.has(directory)) continue
  const manifest = JSON.parse(await readFile(resolve(root, directory, 'package.json'), 'utf8'))
  const names = (await readdir(resolve(root, directory))).filter(name => /^(license|copying|notice)(\.|$)/iu.test(name)).sort()
  if (!names.length) throw Error(`Missing browser dependency license: ${manifest.name}`)
  packages.set(directory, `${manifest.name} ${manifest.version}\n\n` + (await Promise.all(names.map(name => readFile(resolve(root, directory, name), 'utf8')))).join('\n\n'))
}
const notices = [notice, ...packages.values()].join('\n\n---\n\n')
await writeFile(resolve(root, 'notices/preview-dependencies.txt'), notices)
const program = output.outputFiles[0].text + '\n/* ' + notices.replaceAll('*/', '* /') + ' */\n'
const importProgram = importOutput.outputFiles[0].text + '\n/* ' + notices.replaceAll('*/', '* /') + ' */\n'
await writeFile(resolve(root, 'src/preview/workspace.generated.ts'),
  '// Generated by scripts/build-preview-workspace.mjs. No CDN or runtime dependencies.\nexport const workspaceScript = ' + JSON.stringify(program) + '\nexport const importReviewScript = ' + JSON.stringify(importProgram) + '\n')
console.log(`Built Animate UI workspace (${Buffer.byteLength(program)} bytes, offline browser bundle).`)
console.log(`Built Animate UI import review (${Buffer.byteLength(importProgram)} bytes, offline browser bundle).`)
